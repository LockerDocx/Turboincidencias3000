export const ICON_NAMES = Object.keys(MAPS);

/**
 * Devuelve el markup SVG de un icono de píxel.
 * @param {string} name clave de MAPS
 * @returns {string} SVG inline
 */
export function icon(name) {
  const rows = MAPS[name] || MAPS.dot;
  const rects = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w++;
        rects.push(`<rect x="${x}" y="${y}" width="${w}" height="1"/>`);
        x += w;
      } else {
        x++;
      }
    }
  });
  return `<svg viewBox="0 0 ${GRID} ${GRID}" width="100%" height="100%" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${rects.join('')}</svg>`;
}

/**
 * Rellena todos los elementos con [data-icon] del documento (o de un nodo).
 * Si el elemento tiene contenido propio (texto/etiqueta) el icono se antepone.
 */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.iconDone === '1') return;
    const name = el.dataset.icon;
    const svg = icon(name);
    if (el.childElementCount > 0 || el.textContent.trim()) {
      el.insertAdjacentHTML('afterbegin', svg);
    } else {
      el.innerHTML = svg;
    }
    el.dataset.iconDone = '1';
  });
}
